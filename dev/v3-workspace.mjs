import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { BASE, LEFT, RIGHT, ROW, CANVAS, runProbe, enterStudy, openExisting, fold, timeState } from "./cdp.mjs";

await runProbe("v3-workspace", { port: 9351, width: 1440, height: 900 }, async ({ browser, dir, check, expect, shot, log }) => {
  const visible = (selector) => browser.evaluate(`!!document.querySelector(${JSON.stringify(selector)})?.getClientRects().length`);
  const text = (selector) => browser.evaluate(`document.querySelector(${JSON.stringify(selector)})?.textContent || ''`);
  const row = (title) => `${LEFT} button[aria-label=${JSON.stringify(`查看题目 ${title}`)}]`;
  const doubleClick = async (selector) => {
    const box = await browser.box(selector);
    for (const count of [1, 2]) {
      await browser.send("Input.dispatchMouseEvent", { type: "mousePressed", x: box.x, y: box.y, button: "left", buttons: 1, clickCount: count });
      await browser.send("Input.dispatchMouseEvent", { type: "mouseReleased", x: box.x, y: box.y, button: "left", buttons: 0, clickCount: count });
    }
  };
  const tab = (label) => browser.click(label, '[role="tab"]', { exact: true });
  const stored = (title) => browser.evaluate(`new Promise((resolve, reject) => {
    const req = indexedDB.open('gewu-studio');
    req.onerror = () => reject(req.error);
    req.onsuccess = () => { const db = req.result, tx = db.transaction('sessions'); const r = tx.objectStore('sessions').getAll(); r.onsuccess = () => { resolve(r.result.find(s => s.title === ${JSON.stringify(title)})); db.close(); }; };
  })`);
  const detail = `${LEFT} [aria-label="题目原文与图片"]`;
  const pre = 'section[aria-label="简要题解"] pre';
  await browser.send("Browser.grantPermissions", { origin: BASE, permissions: ["clipboardReadWrite", "clipboardSanitizedWrite"] });
  await browser.goto(BASE);
  await enterStudy(browser);
  const title = await browser.evaluate(`document.querySelector(${JSON.stringify(`${LEFT} ${ROW}`)}).getAttribute('aria-label').slice(3,-4)`);
  await browser.clickSelector(row(title));
  check("singleClickDoesNotEnterWorkspace", !(await browser.exists(CANVAS)));
  await doubleClick(row(title));
  await browser.wait(`!!document.querySelector(${JSON.stringify(detail)})`, "double click opens source");
  check("doubleClickOpensSourceAndAnimation", await visible(detail) && await browser.exists(CANVAS));
  check("fullStatementOnLeft", (await text(detail)).includes("小球的射程、最大高度与飞行时间"));
  check("noBottomEditorOrFakeImage", !(await browser.exists(`${LEFT} textarea`)) && !(await browser.exists(`${detail} img`)));
  const heading = await browser.evaluate(`(() => { const h=document.querySelector('header h1'); const r=h.getBoundingClientRect(); return {text:h.textContent, center:r.x+r.width/2, width:innerWidth}; })()`);
  check("sessionNameCenteredInHeader", heading.text === title && Math.abs(heading.center - heading.width / 2) < 10, heading);
  check("noDuplicateCentralStatement", !(await browser.exists('main [aria-label="当前题干"]')));
  const exam = await text(pre);
  check("oneStandardAnswerBlock", await browser.evaluate(`document.querySelectorAll('section[aria-label="简要题解"] pre').length === 1`) && exam.startsWith("解") && exam.includes("答：") && exam.includes("35.35") && exam.includes("5.1") && exam.includes("2.04") && !exam.includes("第 1 步") && !exam.includes("抛体运动可分解"), exam);
  check("detailDefaultClosed", !(await fold(browser, "详细讲解")).panel);
  await browser.clickSelector('section[aria-label="详细讲解"] > button');
  const methods = await text('section[aria-label="详细讲解"] pre');
  check("twoCompleteMethodsInSingleBlock", methods.includes("① 分解运动法") && methods.includes("② 能量与分段运动法") && methods.split("答：").length === 3 && await browser.evaluate(`document.querySelectorAll('section[aria-label="详细讲解"] pre').length === 1`), methods);
  await browser.click("复制详解", 'section[aria-label="详细讲解"] button', { exact: true });
  check("copiesExactDetailText", (await browser.evaluate("navigator.clipboard.readText()")).replace(/\r\n/g, "\n") === methods);
  await browser.clickSelector('section[aria-label="详细讲解"] > button');
  await browser.click("复制题解", 'section[aria-label="简要题解"] button', { exact: true });
  check("copiesExactExamText", (await browser.evaluate("navigator.clipboard.readText()")).replace(/\r\n/g, "\n") === exam);
  await shot("01-standard-answer.png");
  await tab("对话");
  check("chatOnlyInRightPane", await visible(`${RIGHT} [aria-label="追加提问"]`) && !(await browser.exists('main [aria-label="追加提问"]')));
  check("parameterPanelHiddenInChat", !(await visible('[aria-label="参数讲解与调整"]')));
  await browser.clickSelector('button[aria-label="复制题目"]');
  check("copyProblem", (await browser.evaluate("navigator.clipboard.readText()")).includes("20 m/s"));
  check("blankQuestionDisabled", await browser.evaluate(`document.querySelector('button[aria-label="提交提问"]').disabled`));
  await browser.type('textarea[aria-label="追加提问"]', "   ");
  check("whitespaceQuestionDisabled", await browser.evaluate(`document.querySelector('button[aria-label="提交提问"]').disabled`));
  const question = "为什么 45° 时射程最远？";
  await browser.type('textarea[aria-label="追加提问"]', question);
  await tab("动画参数");
  await tab("对话");
  check("draftSurvivesTabSwitch", await browser.evaluate(`document.querySelector('textarea[aria-label="追加提问"]').value === ${JSON.stringify(question)}`));
  const sentAfter = Date.now();
  await browser.clickSelector('button[aria-label="提交提问"]');
  await browser.wait(`document.querySelectorAll('[aria-label="问答记录"]').length === 2`, "new question answered");
  const saved = await stored(title);
  check("questionTimestampStored", saved.questionTimes?.[question] >= sentAfter, saved.questionTimes);
  check("timeOnlyOnUserMessages", await browser.evaluate(`document.querySelectorAll('time').length === 1 && [...document.querySelectorAll('time')].every(t=>t.closest('[aria-label="用户提问"]'))`));
  check("answerHasBlueOutline", await browser.evaluate(`(() => { const c=getComputedStyle(document.querySelector('[aria-label="问题回答"]')); return {border:c.borderWidth,color:c.borderColor}; })()`).then(c => c.border === "1px" && c.color !== "rgb(228, 231, 236)"));
  check("askingDoesNotOpenDetails", !(await fold(browser, "详细讲解")).panel);
  const count = await browser.evaluate(`document.querySelectorAll('[aria-label="问答记录"]').length`);
  await browser.type('textarea[aria-label="追加提问"]', question);
  await browser.clickSelector('button[aria-label="提交提问"]');
  check("duplicateQuestionDoesNotDuplicate", await browser.evaluate(`document.querySelectorAll('[aria-label="问答记录"]').length === ${count}`));
  await shot("02-conversation.png");
  await browser.clickSelector('button[aria-label="编辑题目"]');
  await browser.type('textarea[aria-label="编辑题目内容"]', "取消这个改动");
  await browser.click("取消", '[role="dialog"] button', { exact: true });
  await browser.wait(`!document.querySelector('[role="dialog"]')`, "cancel editor closes");
  check("cancelDoesNotModifyProblem", !(await text('[aria-label="对话题目"]')).includes("取消这个改动"));
  check("editDialogRestoresFocus", await browser.evaluate(`document.activeElement?.getAttribute('aria-label') === '编辑题目'`));
  await browser.clickSelector('button[aria-label="编辑题目"]');
  await browser.type('textarea[aria-label="编辑题目内容"]', " ");
  check("emptyProblemCannotSave", await browser.evaluate(`[...document.querySelectorAll('[role="dialog"] button')].find(b=>b.textContent==='保存题目').disabled`));
  const newStatement = "测试题：从 5 m 高处以 24 m/s、与水平方向成 37° 抛出小球，g 取 10 m/s²。求射程、最大高度与飞行时间。";
  await browser.type('textarea[aria-label="编辑题目内容"]', newStatement);
  await browser.type('input[aria-label="编辑初速度 v₀"]', "24");
  await browser.type('input[aria-label="编辑抛射角 θ"]', "37");
  await browser.type('input[aria-label="编辑初始高度 h₀"]', "5");
  await browser.type('input[aria-label="编辑重力加速度 g"]', "10");
  await shot("03-edit-problem.png");
  await browser.click("保存题目", '[role="dialog"] button', { exact: true });
  await browser.wait(`!document.querySelector('[role="dialog"]')`, "editor closes");
  const vx = 24 * Math.cos(37*Math.PI/180), vy = 24 * Math.sin(37*Math.PI/180);
  const duration = (vy + Math.sqrt(vy*vy+100))/10;
  const expected = [vx*duration, 5+vy*vy/20, duration].map(x=>Number(x.toFixed(2)).toString());
  const updated = await text(pre);
  check("editRecalculatesAllRequestedQuantities", expected.every(n=>updated.includes(n)), {expected,updated});
  check("editRecalculatesAnimation", Math.abs((await timeState(browser)).duration-duration)<0.01);
  check("editUpdatesLeftAndChat", (await text(detail)).includes(newStatement) && (await text('[aria-label="对话题目"]')).includes(newStatement));
  const newTitle = await text('header h1');
  check("editUpdatesDerivedHeaderTitle", newTitle !== title && newTitle.startsWith("测试题"), newTitle);
  await browser.goto(BASE);
  await enterStudy(browser);
  await openExisting(browser, newTitle);
  await tab("对话");
  const restored = await stored(newTitle);
  check("editedProblemAndInitialParamsPersist", restored.problem.statement===newStatement && restored.problem.params.v0===24 && restored.baseParams.h0===5, restored.problem);
  check("questionAndActualTimePersist", restored.questions.includes(question) && restored.questionTimes[question]===saved.questionTimes[question]);
  check("chatTabPreferencePersists", await browser.evaluate(`JSON.parse(localStorage.getItem('gewu-prefs-v2')).rightTab === 'chat'`));
  await browser.clickSelector(row(newTitle));
  await browser.key("Enter", "Enter", 13);
  await browser.wait(`!!document.querySelector(${JSON.stringify(detail)})`, "keyboard activation opens source");
  check("keyboardCanOpenSource", await visible(detail));
  await browser.clickSelector(`${LEFT} button[aria-label="返回题库"]`);
  check("backReturnsLibrary", await visible(`${LEFT} input[aria-label="搜索题库"]`));
  await browser.click("新建题目会话", `${LEFT} button`, {exact:true});
  const imageData = await browser.evaluate(`(() => {const c=document.createElement('canvas');c.width=640;c.height=280;const x=c.getContext('2d');x.fillStyle='#fff';x.fillRect(0,0,640,280);x.fillStyle='#222';x.font='20px sans-serif';x.fillText('QA Physics: v0 = 20 m/s, angle = 30 deg',20,35);x.beginPath();x.moveTo(40,240);x.quadraticCurveTo(280,20,560,240);x.stroke();return c.toDataURL('image/png').split(',')[1];})()`);
  const imageFile = join(dir, "qa-problem.png");
  writeFileSync(imageFile, Buffer.from(imageData,"base64"), {flag:"wx"});
  const doc = await browser.send("DOM.getDocument");
  const node = await browser.send("DOM.querySelector", {nodeId:doc.root.nodeId, selector:'input[type="file"]'});
  await browser.send("DOM.setFileInputFiles", {nodeId:node.nodeId, files:[imageFile]});
  await browser.wait(`!!document.querySelector('img[alt="题目照片缩略预览"]')`, "real photo upload preview");
  await browser.type('textarea[aria-label="题干或提问输入"]', "图片测试：从地面以 20 m/s 的初速度、与水平成 30° 抛出小球，g 取 9.8 m/s²。求射程和飞行时间。");
  await browser.click("识别并生成动画", 'main button', {exact:true});
  await browser.wait(`!!document.querySelector('textarea[aria-label="题目内容（可编辑）"]')`, "photo confirm");
  check("photoFallbackExplicit", (await text('main')).includes("图片不参与本地解析"));
  await browser.click("生成动画与题解", 'main button', {exact:true});
  const photoTitle = await text('header h1');
  await doubleClick(row(photoTitle));
  await browser.wait(`!!document.querySelector(${JSON.stringify(`${detail} img`)})`, "photo in left details");
  const image = await browser.evaluate(`(() => {const i=document.querySelector(${JSON.stringify(`${detail} img`)}); return {width:i.naturalWidth,height:i.naturalHeight,fit:getComputedStyle(i).objectFit,src:i.src};})()`);
  check("originalPhotoDisplayedUncropped", image.width===640 && image.height===280 && image.fit==='contain', {width:image.width,height:image.height,fit:image.fit});
  check("noFakeDiagramExtraction", (await text(detail)).includes("暂不支持自动分离附图"));
  await browser.clickSelector('button[aria-label="放大查看原始题目图片"]');
  await browser.wait(`!!document.querySelector('[role="dialog"] img')`, "photo lightbox");
  check("lightboxPreservesImage", await browser.evaluate(`document.querySelector('[role="dialog"] img').src === ${JSON.stringify(image.src)}`));
  await browser.key("Escape","Escape",27);
  await browser.wait(`!document.querySelector('[role="dialog"]')`, "close lightbox");
  await shot("04-photo-source.png");
  await browser.goto(BASE);
  await enterStudy(browser);
  await doubleClick(row(photoTitle));
  await browser.wait(`!!document.querySelector(${JSON.stringify(`${detail} img`)})`, "photo reload details");
  check("photoPersistsAfterReload", await browser.evaluate(`document.querySelector(${JSON.stringify(`${detail} img`)}).src === ${JSON.stringify(image.src)}`));
  await browser.metrics(390,844,true);
  await browser.clickSelector('button[aria-label="打开参数与对话"]');
  await tab("对话");
  await browser.box('textarea[aria-label="追加提问"]');
  check("mobileChatNoOverflow", await browser.evaluate(`document.documentElement.scrollWidth <= innerWidth && [...document.querySelectorAll('[role="dialog"], [aria-label="题目对话"]')].every(e=>e.scrollWidth<=e.clientWidth+1)`));
  await shot("05-mobile-chat.png");
  log("dataScope", "Temporary Chrome profile only; cloud OCR/AI unavailable, no real user data modified.");
});
